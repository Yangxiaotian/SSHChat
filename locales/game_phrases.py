def _localize_sample(line: str) -> str:
    """Minimal localize helper for ``__main__`` smoke checks."""
    import re
    if line in EXACT_ZH_TO_EN:
        return EXACT_ZH_TO_EN[line]
    for pat, repl in PATTERNS_ZH_TO_EN:
        m = re.match(pat, line)
        if m:
            return repl.format(**m.groupdict())
    return line


